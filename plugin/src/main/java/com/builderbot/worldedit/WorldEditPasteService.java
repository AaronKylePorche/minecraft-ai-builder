package com.builderbot.worldedit;

import com.builderbot.BuilderBotPlugin;
import com.builderbot.util.OrientationUtil;
import com.sk89q.worldedit.EditSession;
import com.sk89q.worldedit.WorldEdit;
import com.sk89q.worldedit.WorldEditException;
import com.sk89q.worldedit.bukkit.BukkitAdapter;
import com.sk89q.worldedit.extent.clipboard.Clipboard;
import com.sk89q.worldedit.extent.clipboard.io.ClipboardFormat;
import com.sk89q.worldedit.extent.clipboard.io.ClipboardFormats;
import com.sk89q.worldedit.extent.clipboard.io.ClipboardReader;
import com.sk89q.worldedit.function.operation.Operation;
import com.sk89q.worldedit.function.operation.Operations;
import com.sk89q.worldedit.math.BlockVector3;
import com.sk89q.worldedit.math.transform.AffineTransform;
import com.sk89q.worldedit.session.ClipboardHolder;
import org.bukkit.Location;
import org.bukkit.entity.Player;

import java.io.File;
import java.io.FileInputStream;
import java.util.logging.Level;

/**
 * Service for loading and pasting WorldEdit schematics.
 * Handles .schem files generated by BuilderGPT.
 */
public class WorldEditPasteService {

    private final BuilderBotPlugin plugin;

    public WorldEditPasteService(BuilderBotPlugin plugin) {
        this.plugin = plugin;
    }

    /**
     * Load and paste a schematic file in front of the player.
     * Uses player's facing direction and mirror orientation system.
     *
     * @param player Player requesting the paste
     * @param schemPath Absolute path to .schem file
     */
    public void pasteSchematicInFrontOfPlayer(Player player, String schemPath) {
        File schemFile = new File(schemPath);

        // Validate file exists
        if (!schemFile.exists() || !schemFile.isFile()) {
            player.sendMessage("§c§lError: §7Schematic file not found: " + schemPath);
            plugin.getLogger().warning("Schematic not found: " + schemPath);
            return;
        }

        try {
            // Load schematic using WorldEdit API
            ClipboardFormat format = ClipboardFormats.findByFile(schemFile);
            if (format == null) {
                player.sendMessage("§c§lError: §7Invalid schematic format");
                return;
            }

            Clipboard clipboard;
            try (ClipboardReader reader = format.getReader(new FileInputStream(schemFile))) {
                clipboard = reader.read();
            }

            // Calculate paste position using orientation system
            Location playerLoc = player.getLocation();
            float yaw = playerLoc.getYaw();

            // Get structure offset from config (default 5 blocks forward)
            double offsetBlocks = plugin.getConfig().getDouble("ai.paste-offset-blocks", 5.0);

            // Use OrientationUtil to place structure in front of player
            // Structure will appear offsetBlocks forward, at player's Y level
            Location pasteOrigin = OrientationUtil.toWorldCoordinates(
                    playerLoc,
                    yaw,
                    offsetBlocks,  // localX: forward
                    0,              // localY: same height
                    0               // localZ: centered
            );

            // Convert to WorldEdit vector
            BlockVector3 pastePos = BlockVector3.at(
                    pasteOrigin.getBlockX(),
                    pasteOrigin.getBlockY(),
                    pasteOrigin.getBlockZ()
            );

            // Create edit session
            com.sk89q.worldedit.world.World world = BukkitAdapter.adapt(player.getWorld());
            try (EditSession editSession = WorldEdit.getInstance()
                    .newEditSessionBuilder()
                    .world(world)
                    .maxBlocks(-1)  // Unlimited blocks (be careful!)
                    .build()) {

                // Apply rotation to align schematic forward axis with player's facing.
                // BuilderGPT schematics are oriented such that a +X length can land to the right;
                // rotating by 90° (instead of 180°) lines up long builds (e.g., bridges) straight ahead.
                ClipboardHolder holder = new ClipboardHolder(clipboard);

                // WorldEdit uses degrees: 0=south, 90=west, 180=north, 270=east
                // Minecraft yaw: 0=south, 90=west, 180=north, 270=east (same!)
                // Rotate 270° (i.e., -90°) to align schematic forward with player's forward; 90° went behind, 180° went left.
                double rotationDegrees = (yaw + 270) % 360;

                // Apply rotation transform
                AffineTransform transform = new AffineTransform();
                transform = transform.rotateY(rotationDegrees);
                holder.setTransform(transform);

                // Paste operation
                Operation operation = holder
                        .createPaste(editSession)
                        .to(pastePos)
                        .ignoreAirBlocks(true)  // Don't overwrite air with air
                        .build();

                Operations.complete(operation);

                // Get dimensions for feedback
                BlockVector3 dimensions = clipboard.getDimensions();
                int blockCount = (int) clipboard.getRegion().getVolume();

                player.sendMessage(String.format(
                        "§a§lSuccess! §7Structure pasted (%dx%dx%d, %d blocks)",
                        dimensions.x(), dimensions.y(), dimensions.z(), blockCount
                ));
                player.sendMessage(String.format(
                        "§7Location: §f%d, %d, %d §7(%.0f blocks in front of you)",
                        pastePos.x(), pastePos.y(), pastePos.z(), offsetBlocks
                ));

                plugin.getLogger().info(String.format(
                        "Pasted schematic for %s: %s (%d blocks at %s)",
                        player.getName(), schemFile.getName(), blockCount, pastePos
                ));
            }

        } catch (WorldEditException e) {
            player.sendMessage("§c§lError: §7WorldEdit failed to paste structure");
            plugin.getLogger().log(Level.SEVERE, "WorldEdit paste error for " + player.getName(), e);
        } catch (Exception e) {
            player.sendMessage("§c§lError: §7Failed to load schematic file");
            plugin.getLogger().log(Level.SEVERE, "Failed to load schematic: " + schemPath, e);
        }
    }
}
